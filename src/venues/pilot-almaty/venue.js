/* ================= шаблон пилота под реальный бар Алматы: ?bar=pilot-almaty =================
   Чистая заготовка камерного бара: один зал со стойкой (без улицы, сцены, погреба и квеста через три зала),
   цены в ₸, колода вопросов для компании за стойкой, афиша выходного дня и барный пропуск с привилегией.
   Брони нет: в барах приходят спонтанно. Гость получает код пропуска после фирменного или авторского коктейля
   или по кнопке «Загляну сегодня» (там же маршрут в 2ГИС, «Написать бару», «Позвать друзей»); бар узнаёт его по коду.
   Всё, что помечено «ЗАПОЛНИТЬ», — места под данные заведения. Пока они не внесены, у гостя на заставке
   плашка «Шаблон пилота», а заявки на бронь идут на тестовые контакты (DEMO_CONTACTS в src/venues/00-registry.js)
   с пометкой «[Тест с демо-страницы]» (сообщения «Загляну сегодня»).

   Чек-лист запуска с заведением:
   1. meta: название, вывеска (коротко — помещается на неон), слоган, адрес, район, часы, сайт/ссылка,
      gis — ссылка на карточку бара в 2ГИС (без неё маршрут ищется по названию и адресу).
   2. contacts: WhatsApp (номер без «+») и Telegram (имя без «@») хостес — после этого убрать demo и badge.
   3. codePrefix (3 латинские буквы) и privilege — что гость получает по коду пропуска.
   4. PRICE: цены в ₸ из прайса бара; MENU_NAMES — их названия для коктейлей карты; SIGNATURE — фирменный коктейль.
   5. events: афиша с реальными датами "гггг-мм-дд" (функция weekend() — только для показа шаблона).
   6. network: бары сети, в которые гость может перейти одним кликом.
   7. python3 tools/build.py, проверить ?bar=pilot-almaty на телефоне и ПК. */
  VENUE_PATCHES.push({
    id: "pilot-almaty",
    base: "hacheden",
    make: base => {
      /* ЗАПОЛНИТЬ: ₸ за порцию по прайсу заведения (сейчас — ориентир для коктейльного бара Алматы) */
      const PRICE = {
        "c-hacheden": 6500, "c-mojito": 4200, "c-daiquiri": 4200, "c-cubalibre": 3500, "c-pinacolada": 4500,
        "c-junglebird": 4800, "c-margarita": 4500, "c-sunrise": 3900, "c-gintonic": 3800, "c-negroni": 4800,
        "c-martini": 4900, "c-collins": 4200, "c-oldfashioned": 5200, "c-manhattan": 5200, "c-sour": 4800,
        "c-pisco": 5500, "c-sidecar": 5200, "c-sangria": 3500, "c-nojito": 2500, "c-irish": 3800,
        "c-toddy": 3500, "c-coffee": 1500, "c-tea": 1800
      };
      /* ЗАПОЛНИТЬ: фирменный коктейль бара — на месте огненного Hacheden (рецепт и 3D-шоу остаются, меняются название и история) */
      const SIGNATURE = {
        name: "Фирменный",
        origin: "Наш бар",
        history: "Фирменный коктейль бара: здесь будет его история — кто придумал, почему так называется и как его подают."
      };
      /* ЗАПОЛНИТЬ (по желанию): свои названия коктейлей карты, например { "c-negroni": "Негрони на выдержке" } */
      const MENU_NAMES = {};
      /* меню заведения: что не продаётся — уберите id из PRICE, коктейль исчезнет из карты */
      const menu = base.menu.filter(c => PRICE[c.id]).map(c => {
        const d = Object.assign({}, c, { price: PRICE[c.id].toLocaleString("ru-RU") });
        if (MENU_NAMES[c.id]) d.name = MENU_NAMES[c.id];
        if (c.id === "c-hacheden") Object.assign(d, SIGNATURE);
        return d;
      });
      /* афиша: ЗАПОЛНИТЬ реальными событиями; пока — ближайшие пятница и суббота, чтобы шаблон всегда показывал свежую афишу */
      const weekend = wd => {
        const d = new Date(); d.setHours(12, 0, 0, 0); d.setDate(d.getDate() + ((wd - d.getDay() + 7) % 7));
        return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
      };
      return {
        meta: {
          name: "Ваш бар",                                  // ЗАПОЛНИТЬ: название заведения
          sign: "Ваш бар",                                  // ЗАПОЛНИТЬ: надпись на неоне (короткая)
          slogan: "Коктейльный бар в Алматы",               // ЗАПОЛНИТЬ
          intro: "Шаблон пилота для коктейльного бара в Алматы: зал со стойкой, барная карта в ₸, колода вопросов для компании, афиша выходных и барный пропуск с комплиментом за визит. Данные заведения ещё не внесены.",
          badge: "Шаблон пилота · данные заведения ещё не внесены",
          city: "Алматы",
          district: "Алматы",                               // ЗАПОЛНИТЬ: район, например «Медеуский район»
          address: "",                                      // ЗАПОЛНИТЬ: улица и дом — видны в «Загляну сегодня», по ним маршрут
          gis: "",                                          // ЗАПОЛНИТЬ: https://2gis.kz/almaty/firm/… — точная карточка бара
          hours: { open: "18:00", close: "02:00", last: "01:30" },   // ЗАПОЛНИТЬ: часы работы и последний заказ
          site: "hacheden.github.io/?bar=pilot-almaty",     // ЗАПОЛНИТЬ: ссылка, которая печатается на сторис
          contacts: Object.assign({}, DEMO_CONTACTS),       // ЗАПОЛНИТЬ: { whatsapp: "77…", telegram: "…" } хостес
          currency: "₸",
          codePrefix: "PLT",                                // ЗАПОЛНИТЬ: 3 буквы заведения
          privilege: "Комплимент от бармена по коду пропуска",   // ЗАПОЛНИТЬ: условие заведения
          demo: true                                        // убрать вместе с badge, когда внесены настоящие контакты
        },
        menu,
        /* один зал со стойкой: комната — камерный зал демо-бара, стойка — Hacheden (rooms/use.txt) */
        rooms: [Object.assign({}, base.rooms.find(r => r.id === "bar"), {
          audio: { rain: 0, fire: 0, clinks: 1 },
          eventStand: { pos: [-.85, -2.25], rot: .14, kind: "counter" }   // рама афиши на стойке; "floor" — мольберт в зале
        })],
        features: { street: false, nook: false, smoke: false, stage: false, cellar: false, quests: false,
          bartenderShow: true, booking: false, liveBar: true },
        events: [
          { title: "Пятница: живой сет", date: weekend(5), time: "21:00", lineup: "ЗАПОЛНИТЬ: музыканты или диджей",
            desc: "Пример события: замените названием, составом и описанием вечера заведения.", accent: "#d6aa5c" },
          { title: "Суббота: вечер авторских коктейлей", date: weekend(6), time: "20:00", lineup: "ЗАПОЛНИТЬ: шеф-бармен или гость",
            desc: "Пример события: что будет, во сколько начало, нужна ли бронь.", accent: "#c8553a" }
        ],
        network: [
          { id: "hacheden", name: "Hacheden", tagline: "Бар, которого нет на карте", district: "Онлайн · спикизи 1920-х" },
          { id: "demo-almaty", name: "Алатау", tagline: "Демо платформы", district: "Алматы" }
        ]
      };
    }
  });
